export const DICTIONARY_SET: Set<string> = new Set(DICTIONARY.map(entry => entry.kana))
export const DICTIONARY_LOOKUP: Lookup = new Map(DICTIONARY.map(entry => [entry.kana, entry]))
// technical approach: both are built once at module load from DICTIONARY, so the
// game checks membership with Set.has and fetches kanji/meaning with Map.get in O(1)

export function validateDictionary(entries: readonly DictEntry[] = DICTIONARY): string[] {
    const problems: string[] = []
    const seen = new Set<string>()
    for (const entry of entries) {
        const chars = Array.from(entry.kana)
        if (chars.length < MIN_WORD_LENGTH || chars.length > MAX_WORD_LENGTH) {
            problems.push(`${entry.kana}: length ${chars.length} is outside ${MIN_WORD_LENGTH}..${MAX_WORD_LENGTH}`)
        }
        const bad = chars.filter(ch => !ALLOWED_SET.has(ch))
        if (bad.length > 0) problems.push(`${entry.kana}: disallowed characters ${bad.join(' ')}`)
        if (seen.has(entry.kana)) problems.push(`${entry.kana}: duplicate`)
        seen.add(entry.kana)
        if (entry.kanji.trim() === '') problems.push(`${entry.kana}: empty kanji`)
        if (entry.meaning.trim() === '') problems.push(`${entry.kana}: empty meaning`)
    }
    return problems
}
